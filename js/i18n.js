const KEY = 'pg.lang';
const listeners = new Set();
let lang = (() => {
  try { const s = localStorage.getItem(KEY); if (s === 'ko' || s === 'en') return s; } catch (_) { /* 저장소 차단 */ }
  return (navigator.language || 'ko').toLowerCase().startsWith('ko') ? 'ko' : 'en';
})();

export const getLang = () => lang;
export const t = (key) => DICT[lang][key] ?? DICT.ko[key] ?? key;
/** {ko, en} 객체 또는 문자열 */
export const pick = (v) => (v && typeof v === 'object' ? v[lang] ?? v.ko : v ?? '');

export function setLang(next) {
  if (next === lang || !DICT[next]) return;
  lang = next;
  try { localStorage.setItem(KEY, lang); } catch (_) { /* 무시 */ }
  applyI18n();
  listeners.forEach((fn) => fn(lang));
}
export const onLang = (fn) => listeners.add(fn);

/** data-i18n / data-i18n-ph / data-i18n-label 일괄 반영 */
export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-label]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nLabel)); el.title = t(el.dataset.i18nLabel); });
}
